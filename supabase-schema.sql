-- Our Teacher School database
create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title_km text not null,
  title_en text,
  content_km text,
  content_en text,
  cover_url text,
  published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.teachers (
  id bigint generated by default as identity primary key,
  name_km text not null,
  name_en text,
  subject_km text,
  subject_en text,
  bio_km text,
  bio_en text,
  photo_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title_km text,
  title_en text,
  image_url text not null,
  category text,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  title_km text not null,
  title_en text,
  youtube_id text not null,
  description_km text,
  published boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_school_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_school_admin() from public;
grant execute on function public.is_school_admin() to authenticated;

alter table public.news enable row level security;
alter table public.teachers enable row level security;
alter table public.gallery enable row level security;
alter table public.videos enable row level security;
alter table public.admin_users enable row level security;

grant select on public.news, public.teachers, public.gallery, public.videos to anon, authenticated;
grant insert, update, delete on public.news, public.teachers, public.gallery, public.videos to authenticated;
grant select on public.admin_users to authenticated;

drop policy if exists "users read own admin grant" on public.admin_users;
create policy "users read own admin grant" on public.admin_users
  for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "public read published news" on public.news;
create policy "public read published news" on public.news
  for select to anon, authenticated
  using (published = true);
drop policy if exists "admin manage news" on public.news;
create policy "admin manage news" on public.news
  for all to authenticated
  using (public.is_school_admin())
  with check (public.is_school_admin());

drop policy if exists "public read teachers" on public.teachers;
create policy "public read teachers" on public.teachers
  for select to anon, authenticated
  using (true);
drop policy if exists "admin manage teachers" on public.teachers;
create policy "admin manage teachers" on public.teachers
  for all to authenticated
  using (public.is_school_admin())
  with check (public.is_school_admin());

drop policy if exists "public read gallery" on public.gallery;
create policy "public read gallery" on public.gallery
  for select to anon, authenticated
  using (published = true);
drop policy if exists "admin manage gallery" on public.gallery;
create policy "admin manage gallery" on public.gallery
  for all to authenticated
  using (public.is_school_admin())
  with check (public.is_school_admin());

drop policy if exists "public read videos" on public.videos;
create policy "public read videos" on public.videos
  for select to anon, authenticated
  using (published = true);
drop policy if exists "admin manage videos" on public.videos;
create policy "admin manage videos" on public.videos
  for all to authenticated
  using (public.is_school_admin())
  with check (public.is_school_admin());

